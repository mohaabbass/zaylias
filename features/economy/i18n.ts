export type EconomyTranslation = (typeof economyTranslations)[Locale] &
  SharedTranslation;

export function getCategoryLabel(locale: Locale, value: string) {
  const normalizedValue = normalizeCategoryValue(value);
  const categories = [
    ...economyTranslations[locale].expenseCategories,
    ...economyTranslations[locale].incomeCategories,
  ];

  return (
    categories.find((category) => category.value === normalizedValue)?.label ??
    value
  );
}
